/* Bridge between the store (window.Makro) and the account area copied from fsd-selfcare (selfcare/js/*).
   Own file (not generated by tools/sync.py). Load order: store.js, i18n-stub.js, data.js, shop-data.js, ui.js, THIS FILE,
   then account.js, acctmenu.js, addrdrawer.js, pages/*.js (pages capture UI.toast when they load, so the override below comes first).

   It recreates just the part of selfcare's `App` that the account island, the account menu and the address drawer use
   (the shell, router, header, nav and shop of selfcare are NOT ported):
     App.S (reactive state built from MockData), reset, register/pages, isAdmin/isOwner/me/list, addrTitle/addrLine/addressName,
     selectable/currentAddress, go, render (re-sync only: the store header is Vue and reacts to App.S by itself), cart.count.
   One source of truth for the delivery address: App.S.addressId. It is validated by currentAddress(), stored in
   localStorage ("sc-address", as in selfcare) and mirrored to Makro.delivery.address (cart, checkout, order, product page).

   It also tags the elements Fresh teleports to <body> from the three islands with the class `sc` (see css/mk-account.css and
   selfcare/css/*.css: all copied rules apply only inside `.sc`). */
;(function () {
  const M = window.Makro
  const clone = (o) => JSON.parse(JSON.stringify(o))
  const mobile = () => matchMedia('(max-width: 768px)').matches
  const ls = {
    get(k) { try { return localStorage.getItem(k) } catch (e) { return null } },
    set(k, v) { try { localStorage.setItem(k, v) } catch (e) {} },
  }

  /* toasts: use the store's own toast (one look, one stack) instead of selfcare's body-level .toast */
  UI.toast = (msg) => M.toast(msg)

  let booted = false
  const App = (window.App = {
    S: Vue.reactive({}),
    pages: {},
    handlers: {},
    reset() {
      const d = clone(MockData), keep = App.S
      Object.assign(App.S, {
        company: d.company, staff: d.staff, authz: d.authz, payments: d.payments, agreements: d.agreements, addresses: d.addresses,
        users: d.users, orders: d.orders, credits: d.credits, card: d.card,
        lists: clone(ShopData.lists), cart: {}, addressId: keep.addressId || 'a1', lang: 'cs',
        role: keep.role || 'owner', scenario: keep.scenario || 'normal', pop: false, cartOpen: false,
        scn: keep.scn !== undefined ? keep.scn : innerWidth >= 1500, type: keep.type || 'figma', rev: keep.rev || 0,
      })
    },
    /* "Obnovit ukázková data": fresh mock data, role / list state / panel state are kept, the address choice is forgotten */
    resetData() {
      App.S.addressId = undefined
      ls.set('sc-address', '')
      const keep = { role: App.S.role, scenario: App.S.scenario, scn: App.S.scn }
      App.reset()
      Object.assign(App.S, keep)
    },
    register(id, def) { App.pages[id] = def },
    on(name, fn) { App.handlers[name] = fn },
    /* Vlastník and Správce účtu both have admin rights; only the owner is the top role */
    isAdmin: () => App.S.role === 'owner' || App.S.role === 'admin',
    isOwner: () => App.S.role === 'owner',
    /* the user the prototype "is" for the selected role */
    me: () => App.S.users.find((u) => u.id === ({ owner: 'u1', admin: 'u6', buyer: 'u2', viewer: 'u7' })[App.S.role]),
    list: (arr) => (App.S.scenario === 'empty' ? [] : arr),
    /* delivery addresses: "Název provozovny" is optional, so the title falls back to the company trading name, then to street + city */
    addrLine: (a) => a.street + ', ' + a.zip + ' ' + a.city,
    addrTitle: (a) => a.name || App.S.company.tradeName || a.street + ', ' + a.city,
    addressName: (id) => { const a = App.S.addresses.find((x) => x.id === id); return a ? App.addrTitle(a) : '—' },
    /* active addresses the current user may use: owner/admin/viewer (and buyers with access "all") see all, a buyer only the assigned ones; main address first */
    selectable() {
      const me = App.me(), all = !me || me.addresses === 'all' || App.isAdmin()
      return App.S.addresses.filter((a) => !a.blocked && (all || me.addresses.includes(a.id))).sort((x, y) => (y.main ? 1 : 0) - (x.main ? 1 : 0))
    },
    currentAddress() { const a = App.selectable(); return a.find((s) => s.id === App.S.addressId) || a.find((s) => s.main) || a[0] || null },
    /* header label: optional "Název provozovny" + street, zip city of the effective current address */
    addrParts() {
      const a = App.currentAddress()
      return a ? { name: a.name || '', line: App.addrLine(a) } : { name: '', line: 'Žádná dodací adresa' }
    },
    go(id) { location.hash = '#/ucet/' + id },
    /* selfcare re-renders its whole shell here; the store's header is reactive, so only a counter is bumped */
    render() { App.S.rev++ },
    cart: { count: () => M.totals().lines },
  })

  /* keeps the stored choice, App.S.addressId and Makro.delivery.address in sync with the data, whatever changes it (islands included) */
  Vue.watchEffect(() => {
    if (!App.S.addresses) return
    const cur = App.currentAddress()
    if (cur && App.S.addressId !== cur.id) App.S.addressId = cur.id // selected one was deactivated / removed / no longer allowed
    M.delivery.address = cur ? App.addrLine(cur) : 'Žádná dodací adresa'
    if (cur && booted) ls.set('sc-address', cur.id)
  })

  /* boot: restore the stored address (validated by currentAddress()), then build the state */
  App.S.addressId = ls.get('sc-address') || undefined
  App.reset()
  booted = true

  /* narrow screens: the account menu button navigates to the hub page instead of opening the dropdown */
  matchMedia('(max-width: 768px)').addEventListener('change', () => { if (window.AcctMenu) AcctMenu.sync(); App.render() })
  window.addEventListener('hashchange', () => { if (window.AddrDrawer) AddrDrawer.close(true) })

  /* ---- teleported content ----
     Fresh renders menus, drawers and dialogs into <body>, outside the .sc wrapper. Tag the elements that come from the three
     islands with `sc` so the scoped copy of the selfcare CSS applies to them (and only to them). The island is recognised by the
     container of the Vue app that created the element; without Vue's dev hooks, by classes only the account area uses. */
  const HOSTS = '#acct-host, #acct-menu-host, #addr-drawer-host'
  const MARKERS = '.am, .addr-drawer, .acct-drawer, .fld2, .acct-danger, .acct-radio, .fset, .row2, .row3, .sub-sec, .lbl-t, .kv, .addr-box, .muted, .note, .lead, .lead2, .cell-sub, .days, .radios'
  const fromIsland = (el) => {
    const c = el.__vueParentComponent, host = c && c.appContext && c.appContext.app && c.appContext.app._container
    return host ? host.matches(HOSTS) : el.matches(MARKERS) || !!el.querySelector(MARKERS)
  }
  const keepClass = new MutationObserver((ms) => ms.forEach((m) => { if (!m.target.classList.contains('sc')) m.target.classList.add('sc') }))
  const tag = (el) => {
    if (el.nodeType !== 1 || el.tagName === 'SCRIPT' || el.id === 'app' || el.classList.contains('sc') || !fromIsland(el)) return
    el.classList.add('sc')
    keepClass.observe(el, { attributes: true, attributeFilter: ['class'] }) // Vue may rewrite the class attribute of its own elements
  }
  new MutationObserver((ms) => ms.forEach((m) => m.addedNodes.forEach(tag))).observe(document.body, { childList: true })
})()
