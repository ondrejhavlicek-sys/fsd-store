/* Czech-only stand-in for fsd-selfcare's js/i18n.js (a 90 KB CS/EN/VI dictionary that is NOT copied).
   The copied files only call I18N.t(s), I18N.apply(el) and I18N.set(lang); texts are the Czech source strings.
   Own file (not generated by tools/sync.py). The language switch is not part of the store prototype:
   picking another language on "Osobní údaje" falls back to Czech with a note. */
window.I18N = {
  t: (s) => s,
  apply() {},
  set(lang) {
    if (lang === 'cs') return
    Vue.nextTick(() => {
      if (window.App) App.S.lang = 'cs'
      if (window.UI) UI.toast('Jazykové verze nejsou součástí prototypu obchodu.')
    })
  },
}
